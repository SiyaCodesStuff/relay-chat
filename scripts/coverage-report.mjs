import { readFile, writeFile } from "node:fs/promises";

const workspaces = ["packages/shared", "apps/api", "apps/web"];
const rows = [];
const totals = [];
for (const workspace of workspaces) {
  const summary = JSON.parse(await readFile(`${workspace}/coverage/coverage-summary.json`, "utf8"));
  for (const [file, value] of Object.entries(summary)) {
    if (file === "total") continue;
    rows.push({ file: file.slice(process.cwd().length + 1), ...value.lines });
  }
  console.log(`${workspace}: ${summary.total.lines.pct}% lines`);
  totals.push(`| ${workspace} | ${summary.total.lines.pct}% | 80% |`);
}
rows.sort((a, b) => a.pct - b.pct || a.file.localeCompare(b.file));
const table = [
  "| File | Lines | Covered / total |",
  "| --- | ---: | ---: |",
  ...rows.map(({ file, pct, covered, total }) => `| ${file} | ${pct}% | ${covered} / ${total} |`),
];
const report = [
  "# Coverage",
  "",
  "Generated by `npm run test:coverage`; includes all workspace source files.",
  "",
  "| Workspace | Lines | Required |",
  "| --- | ---: | ---: |",
  ...totals,
  "",
  ...table,
  "",
  "Three weakest files:",
  "",
  ...rows.slice(0, 3).map((row) => `- ${row.file}: ${row.pct}% lines`),
  "",
];
await writeFile("docs/coverage.md", report.join("\n"));
console.log(table.join("\n"));
if (rows.length === 0) process.exitCode = 1;
